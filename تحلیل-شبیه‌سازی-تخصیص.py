def cost(a, rate, cw):
    """هزینه‌ی کل (همت): ریالی + ارزی تسعیرشده + کربن‌ارزش‌گذاری‌شده."""
    c_rial = a['c'] * (1 - a['fx'])
    c_fx   = a['c'] * a['fx'] * (rate / BASE)
    c_co2  = (a['co2'] * 1000) * cw * rate / HMT          # تن × دلار بر تن × نرخ ⇒ ریال ⇒ همت
    return c_rial + c_fx + c_co2

def score(a, rate, cw):
    return cost(a, rate, cw) / a['svc']                   # هزینه بر واحد خدمت

rows, rank_by, top3 = [], defaultdict(list), defaultdict(int)
